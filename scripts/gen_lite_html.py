import json, base64, os

with open('data/xunzhilu_clusters.json') as f:
    cl = json.load(f)
with open('data/xunzhilu_pca.json') as f:
    pca = json.load(f)

il = cl['image_labels']
cs = cl['cluster_sizes']
rl = cl['record_labels']
COLORS = ['#e94560','#0f3460','#533483','#00d2d3','#ff9f43','#ee5a24','#a55eea','#2ed573']

scatter = [[round(v[0],1), round(v[1],1), il.get(f,0)] for f,v in pca.items()]
scatter_b64 = base64.b64encode(json.dumps(scatter).encode()).decode()

stats = []
for cid_str in sorted(cs.keys(), key=lambda x: int(x)):
    cid = int(cid_str)
    cnt = cs[cid_str]
    nrec = len([r for r,c in rl.items() if c==cid])
    recs = sorted([r for r,c in rl.items() if c==cid])
    stats.append({'id':cid,'imgs':cnt,'records':nrec,'samples':recs[:8]})
stats_b64 = base64.b64encode(json.dumps(stats).encode()).decode()

